def _mount_arm_chain_mismatch(mount_root: ET.Element, collision_scene_profile: str) -> str | None:
    """First arm joint whose origin differs between the mount URDF and the planning model.

    Wrist cameras are posed by planning FK times the mount URDF's link6 chain
    and the self filter renders the mount URDF, so a standard RM65 mount with
    an RM65-6F planning model (or the reverse) would misplace both by the
    17.2 mm sensor length.
    """
    from robot_motion.rm65.scene_profiles import build_dual_arm_scene_profile

    planning_root = ET.parse(build_dual_arm_scene_profile(collision_scene_profile).urdf_path).getroot()

    def origins(root, names):
        joints = {joint.get("name"): joint for joint in root.findall("joint")}
        result = []
        for name in names:
            origin = None if name not in joints else joints[name].find("origin")
            if origin is None:
                return None, name
            result.append((np.asarray((origin.get("xyz") or "0 0 0").split(), dtype=float),
                           np.asarray((origin.get("rpy") or "0 0 0").split(), dtype=float)))
        return result, None

    for side, planning_prefix in (("left", "arm_joint"), ("right", "right_arm_joint")):
        mount_names = [f"{side}_arm_joint{index}" for index in range(1, 7)]
        mount, missing = origins(mount_root, mount_names)
        if mount is None:
            return f"lacks the {missing} origin"
        planning, missing = origins(planning_root, [f"{planning_prefix}{index}" for index in range(1, 7)])
        if planning is None:
            return f"cannot be compared: the planning model lacks {missing}"
        for name, (mount_xyz, mount_rpy), (planning_xyz, planning_rpy) in zip(mount_names, mount, planning):
            if np.abs(mount_xyz - planning_xyz).max() > 1e-9 or np.abs(mount_rpy - planning_rpy).max() > 1e-9:
                length = float(np.linalg.norm(mount_xyz)) - float(np.linalg.norm(planning_xyz))
                return f"{name} differs from the planning model ({length * 1000.0:+.1f} mm)"
    return None


def _validate_point_grasp_capture_urdf(
    parser: argparse.ArgumentParser,
    *,
    urdf_path: Path,
    collision_scene_profile: str,
) -> None:
    try:
        root = ET.parse(urdf_path).getroot()
    except (OSError, ET.ParseError) as error:
        parser.error(f"cannot parse --camera-mount-urdf: {error}")

    missing_meshes: set[str] = set()
    for mesh in root.findall(".//mesh"):
        filename = str(mesh.get("filename", "")).strip()
        if not filename:
            continue
        parsed = urlparse(filename)
        if parsed.scheme not in {"", "file"}:
            continue
        raw_path = unquote(parsed.path) if parsed.scheme == "file" else filename
        mesh_path = Path(raw_path)
        if not mesh_path.is_absolute():
            mesh_path = urdf_path.parent / mesh_path
        if not mesh_path.is_file():
            missing_meshes.add(str(mesh_path))
    if missing_meshes:
        missing_preview = sorted(missing_meshes)
        suffix = "" if len(missing_preview) <= 8 else " ..."
        parser.error(
            "--camera-mount-urdf references missing mesh assets: "
            f"{missing_preview[:8]}{suffix}"
        )

    if collision_scene_profile not in DMTAC_SCENE_PROFILES:
        return
    mismatch = _mount_arm_chain_mismatch(root, collision_scene_profile)
    if mismatch is not None:
        parser.error(
            f"--camera-mount-urdf {mismatch}; the mount URDF and --collision-scene-profile "
            f"{collision_scene_profile} must describe the same RM65 arm model")
    visual_names = {
        str(visual.get("name", "")).strip()
        for visual in root.findall(".//visual")
    }
    missing = sorted(_REQUIRED_DMTAC_CAPTURE_VISUALS - visual_names)
    if missing:
        parser.error(
            f"--collision-scene-profile {collision_scene_profile} "
            "requires --camera-mount-urdf to contain both arms' reviewed "
            f"DMTAC capture geometry; missing visuals: {missing}"
        )


def _graspgenx_mode_was_explicit(argv: list[str] | None) -> bool:
    """Return whether the caller explicitly selected a GraspGenX mode.

    The default is intentionally in-process, but that default must stay inert
    for VGN/GraspNet and camera-only launches.  Only an explicit mode flag is
    therefore validated against the selected point-grasp backend.
    """

    tokens = sys.argv[1:] if argv is None else argv
    return any(
        token == "--graspgenx-mode"
        or token.startswith("--graspgenx-mode=")
        for token in tokens
    )


def _absolute_socket_path(
    parser: argparse.ArgumentParser,
    value: Path,
) -> Path:
    expanded = value.expanduser()
    if not expanded.is_absolute():
        parser.error("--socket-path must be an absolute path")
    return Path(os.path.abspath(expanded))


def _absolute_managed_directory(
    parser: argparse.ArgumentParser,
    value: Path,
    *,
    flag: str,
) -> Path:
    expanded = value.expanduser()
    if not expanded.is_absolute():
        parser.error(f"{flag} must be an absolute path")
    path = Path(os.path.abspath(expanded))
    try:
        info = os.lstat(path)
    except OSError:
        parser.error(f"{flag} is not an existing directory: {path}")
    if not stat.S_ISDIR(info.st_mode) or stat.S_ISLNK(info.st_mode):
        parser.error(f"{flag} must be a real directory, not a symlink: {path}")
    if info.st_mode & stat.S_IWOTH:
        parser.error(f"{flag} cannot be world-writable: {path}")
    return path


