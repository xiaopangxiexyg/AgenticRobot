"""Terminal input and loop-rate observation for policy deployment.

These utilities expose operator keyboard input and a display-only frequency
estimate.  They do not own deployment state, action authority, or resources
beyond restoring the terminal mode they temporarily change.
"""

from __future__ import annotations

import select
import sys
import termios
import tty

from typing_extensions import Self


class NonBlockingKeyboard:
    def __init__(self) -> None:
        self._fd: int | None = None
        self._old_settings: list[object] | None = None

    def __enter__(self) -> Self:
        if sys.stdin.isatty():
            self._fd = sys.stdin.fileno()
            self._old_settings = termios.tcgetattr(self._fd)
            tty.setcbreak(self._fd)
        return self

    def poll(self) -> str | None:
        if self._fd is None:
            return None
        readable, _, _ = select.select([sys.stdin], [], [], 0.0)
        if not readable:
            return None
        return sys.stdin.read(1)

    def __exit__(self, exc_type: object, exc: object, traceback: object) -> None:
        if self._fd is not None and self._old_settings is not None:
            termios.tcsetattr(self._fd, termios.TCSADRAIN, self._old_settings)


class LoopRate:
    def __init__(self) -> None:
        self._last: float | None = None
        self.hz = 0.0

    def tick(self, now: float) -> float:
        if self._last is not None:
            dt = max(float(now - self._last), 1e-9)
            instant = 1.0 / dt
            self.hz = instant if self.hz <= 0.0 else 0.2 * instant + 0.8 * self.hz
        self._last = float(now)
        return float(self.hz)
